package com.personal.rebooked.homepage.sections;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.personal.rebooked.book.models.Book;
import com.personal.rebooked.category.models.Category;
import com.personal.rebooked.homepage.HomepageBooks;
import com.personal.rebooked.homepage.HomepageCache;
import com.personal.rebooked.homepage.dto.AiPick;
import com.personal.rebooked.homepage.dto.PickRef;
import com.personal.rebooked.service.AiService;
import com.personal.rebooked.utils.Constants;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.data.mongodb.core.MongoTemplate;
import org.springframework.data.mongodb.core.aggregation.Aggregation;
import org.springframework.stereotype.Component;

import java.time.Duration;
import java.util.*;

import static org.springframework.data.mongodb.core.query.Criteria.where;

/**
 * §24e global AI picks with reasons. Generated by the daily job only; requests just read the snapshot. A failed run
 * keeps the previous picks (their TTL is extended) and never surfaces as an error.
 */
@Slf4j
@Component
@RequiredArgsConstructor
public class AiPicksSection {
    public static final String KEY = "homepage:ai-picks";
    static final String FAILURES_KEY = "homepage:ai-picks:failures";
    static final Duration TTL = Duration.ofHours(48);
    static final int POOL_EACH = 20;
    static final int DESCRIPTION_MAX = 300;
    static final int ALERT_AFTER_FAILURES = 3;

    private final HomepageCache cache;
    private final HomepageBooks books;
    private final TrendingSection trending;
    private final MongoTemplate mongoTemplate;
    private final AiService aiService;
    private final ObjectMapper objectMapper;

    /** The current picks; empty until the job has run once. Never calls the model. */
    public List<AiPick> read() {
        return resolve(cache.get(KEY, new TypeReference<List<PickRef>>() {}).orElse(List.of()));
    }

    /** GET /book/ai-picks: just the books. */
    public List<Book> books() {
        return read().stream().map(AiPick::book).toList();
    }

    public boolean exists() {
        return cache.exists(KEY);
    }

    /** Live ACTIVE books for the stored picks, in order, with their reasons. */
    public List<AiPick> resolve(List<PickRef> refs) {
        if (refs == null || refs.isEmpty()) return List.of();
        Map<String, Book> byId = new HashMap<>();
        for (Book b : books.active(refs.stream().map(PickRef::id).toList())) byId.put(b.getId(), b);
        List<AiPick> picks = new ArrayList<>();
        for (PickRef ref : refs) {
            Book b = byId.get(ref.id());
            if (b != null) picks.add(new AiPick(b, ref.reason()));
        }
        return picks;
    }

    /** The daily job. True when new picks were saved. */
    public boolean build() {
        List<Book> pool = candidatePool();
        if (pool.isEmpty()) {
            log.info("AI picks skipped: no ACTIVE books");
            return false;
        }
        try {
            String response = aiService.pickHomepageBooks(promptJson(pool, objectMapper));
            List<PickRef> picks = AiPicksParser.parse(response, new HashSet<>(HomepageBooks.ids(pool)));
            cache.put(KEY, picks, TTL);
            cache.evict(FAILURES_KEY);
            log.info("AI picks saved: {} picks from {} candidates", picks.size(), pool.size());
            return true;
        } catch (Exception e) {
            cache.expire(KEY, TTL);
            long failures = cache.increment(FAILURES_KEY, Duration.ofDays(7));
            if (failures >= ALERT_AFTER_FAILURES) {
                log.error("ALERT: AI picks job failed {} runs in a row; yesterday's picks stay live. Last error: {}",
                        failures, e.toString());
            } else {
                log.warn("AI picks job failed ({} in a row); keeping the previous picks: {}", failures, e.toString());
            }
            return false;
        }
    }

    /** About 60 ACTIVE books: 20 trending, 20 newest and 20 random, without repeats. */
    List<Book> candidatePool() {
        List<Book> pool = new ArrayList<>();
        HomepageBooks.fill(pool, POOL_EACH, trending.read(), b -> true);
        HomepageBooks.fill(pool, POOL_EACH * 2, books.newest(POOL_EACH * 2, false, null), b -> true);
        List<Book> random = mongoTemplate.aggregate(Aggregation.newAggregation(
                Aggregation.match(where("status").is(Constants.BookStatus.ACTIVE)),
                Aggregation.sample(POOL_EACH * 2)), Book.class, Book.class).getMappedResults();
        HomepageBooks.fill(pool, POOL_EACH * 3, random, b -> true);
        return pool;
    }

    /** id, title, author, description (≤ 300 chars), categories and condition for each book. */
    static String promptJson(List<Book> pool, ObjectMapper mapper) throws Exception {
        List<Map<String, String>> rows = new ArrayList<>();
        for (Book b : pool) {
            Map<String, String> row = new LinkedHashMap<>();
            row.put("id", b.getId());
            row.put("title", b.getTitle());
            row.put("author", b.authorNames());
            String description = b.getDescription() == null ? "" : b.getDescription().trim();
            row.put("description", description.length() > DESCRIPTION_MAX ? description.substring(0, DESCRIPTION_MAX) : description);
            row.put("categories", b.getCategories() == null ? "" : String.join(", ",
                    b.getCategories().stream().filter(Objects::nonNull).map(Category::getName).filter(Objects::nonNull).toList()));
            row.put("condition", b.getCondition() == null ? "" : b.getCondition().name());
            rows.add(row);
        }
        return mapper.writeValueAsString(rows);
    }
}
